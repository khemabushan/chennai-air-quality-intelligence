"""Phase 1: data audit + EDA figures -> reports/data_audit.md and results/figures/."""
import json

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

from src.config import FIGURES_DIR, METRICS_DIR, POLLUTANTS, RAW_SHA256, REPORTS_DIR, STATIONS
from src.data_loader import load_raw, verify_raw_hashes
from src.data_validation import (check_schema, constant_runs, longest_gaps, pm25_gt_pm10,
                                 station_summary, value_checks)
from src.preprocessing import to_daily_calendar

sns.set_theme(style="whitegrid", context="notebook")


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(round(v, 2)) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def figures(raw: pd.DataFrame, daily: pd.DataFrame) -> None:
    fig, axes = plt.subplots(6, 1, figsize=(12, 14), sharex=True, sharey=True)
    for ax, st in zip(axes, STATIONS):
        g = daily[daily.station == st]
        ax.plot(g["date"], g["PM2.5"], lw=0.8, color="#2a6f97")
        ax.set_title(st, loc="left", fontsize=10)
        ax.set_ylabel("PM2.5")
    fig.suptitle("Daily PM2.5 by station (gaps = missing dates)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_pm25_timeseries.png", dpi=110)
    plt.close(fig)

    fig, axes = plt.subplots(1, 5, figsize=(18, 3.5))
    for ax, col in zip(axes, POLLUTANTS):
        sns.histplot(raw[col].dropna(), bins=50, ax=ax, color="#468faf")
        ax.set_title(col)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_pollutant_distributions.png", dpi=110)
    plt.close(fig)

    piv = daily.assign(month=daily["date"].dt.to_period("M").astype(str)).groupby(["station", "month"])["observed"].mean().unstack()
    fig, ax = plt.subplots(figsize=(14, 3.6))
    sns.heatmap(1 - piv, cmap="Reds", vmin=0, vmax=1, ax=ax, cbar_kws={"label": "share of days missing"})
    ax.set(xlabel="month", ylabel="", title="Missing calendar days per station and month")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_missing_dates_heatmap.png", dpi=110)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    sns.heatmap(raw[POLLUTANTS].corr(), annot=True, fmt=".2f", cmap="vlag", center=0, ax=ax)
    ax.set_title("Pollutant correlation (Pearson, all stations)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_correlation_heatmap.png", dpi=110)
    plt.close(fig)

    m = raw.assign(month=raw["date"].dt.month).groupby(["month", "station"])["PM2.5"].mean().unstack()
    fig, ax = plt.subplots(figsize=(9, 4))
    m.plot(ax=ax, marker="o")
    ax.set(xlabel="month", ylabel="mean PM2.5", title="Seasonal pattern: monthly mean PM2.5")
    ax.set_xticks(range(1, 13))
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_seasonality_monthly.png", dpi=110)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(9, 4))
    sns.boxplot(data=raw, x="station", y="PM2.5", ax=ax, color="#89c2d9", fliersize=2)
    ax.set_title("PM2.5 distribution by station")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "eda_station_boxplot.png", dpi=110)
    plt.close(fig)


def main() -> None:
    hashes = verify_raw_hashes()
    raw = load_raw()
    daily = to_daily_calendar(raw)
    schema = check_schema(raw)
    summ = station_summary(raw)
    gaps = longest_gaps(raw)
    vals = value_checks(raw)
    ratio = pm25_gt_pm10(raw)
    runs = pd.concat([constant_runs(raw, c, 3) for c in POLLUTANTS], ignore_index=True)
    run_counts = runs.groupby("pollutant").agg(runs_ge3=("length", "size"), longest=("length", "max")).reset_index()
    exact_dupes = int(raw.duplicated().sum())
    figures(raw, daily)

    summary = {"rows": len(raw), "stations": raw.station.nunique(), "first": str(raw.date.min().date()),
               "last": str(raw.date.max().date()), "hash_ok": all(hashes.values()),
               "pm25_gt_pm10_pct": round(100 * (raw["PM2.5"] > raw["PM10"]).mean(), 1),
               "missing_calendar_days": int((~daily.observed).sum())}
    (METRICS_DIR / "audit_summary.json").write_text(json.dumps(summary, indent=2))

    report = f"""# Data Audit — Chennai Air Quality (Mendeley DOI 10.17632/br5dyxm7c6.1)

Generated by `python -m src.audit`. All numbers below are computed from the original CSVs in
`data/raw/`, which are kept byte-for-byte unchanged (SHA-256 verified on every run).

## 1. Provenance

* Source: *Hybrid Prophet-XGBoost Forecasting for Urban Air Quality with Real-Time Data Integration
  for Chennai*, Mendeley Data, DOI [10.17632/br5dyxm7c6.1](https://data.mendeley.com/datasets/br5dyxm7c6/1).
* Files used: the six CSVs in `Air Pollutants Historic Data (2022-2024)/`. The archive's Python code,
  metrics file and PDF report were **not** used.
* The publisher does not document whether values were cleaned, averaged or imputed before release
  (several values end in `.5`, suggesting averaging of two readings). The data must therefore **not**
  be described as untouched raw sensor output.

| file | SHA-256 | verified |
|---|---|---|
""" + "\n".join(f"| {k} | `{v}` | {hashes[k]} |" for k, v in RAW_SHA256.items()) + f"""

## 2. Structure

* Rows: **{len(raw)}**, stations: **{raw.station.nunique()}**, columns: `Date, MONITORING STATION, PM2.5, PM10, NO2, SO2, O3`.
* Date range: **{summary['first']} → {summary['last']}**. Schema problems: {schema or 'none'}.
* Exact duplicate rows: {exact_dupes}. Duplicate (station, date) pairs: {int(summ.duplicate_dates.sum())}.
* Units are not stated in the source; PM values are consistent with µg/m³ (CPCB convention).

## 3. Coverage per station

{md(summ)}

Total missing station-days on the 2022-01-01 … 2024-12-31 calendar: **{summary['missing_calendar_days']}**
of {len(daily)}. See `results/figures/eda_missing_dates_heatmap.png`.

### Longest gaps

{md(gaps)}

## 4. Value checks

{md(vals)}

* No negative values were found where the table shows `negative = 0`.
* Upper outliers (beyond Q3 + 3·IQR) are retained: they are plausible pollution episodes (e.g. Diwali,
  winter inversions) and removing them would bias evaluation. They are flagged, not altered.

## 5. PM2.5 greater than PM10

Physically PM2.5 is a subset of PM10, so PM2.5 > PM10 indicates instrument, calibration or
processing issues. Overall share: **{summary['pm25_gt_pm10_pct']}%** of rows.

{md(ratio)}

The share is so high (median PM2.5 {raw['PM2.5'].median():.0f} vs median PM10 {raw['PM10'].median():.0f})
that a **systematic column-labelling swap or unit/processing issue in the published files is plausible**;
typical Chennai CPCB annual means are higher for PM10 than PM2.5. This cannot be verified from the
archive, so the columns are used **as labelled** and every result in this project refers to "PM2.5 as
published in the dataset". This is the most important limitation of the study.

## 6. Repeated constant readings (runs of ≥ 3 identical consecutive records)

{md(run_counts)}

Longest runs:

{md(runs.head(10))}

Low-valued constant runs in SO2/O3 suggest instrument floors or rounding; they are kept as-is.

**QC rule applied to the target:** a PM2.5 value repeated on ≥ 14 consecutive calendar days is treated
as a filler, not a measurement, and masked to missing in `data/processed/` (flag `pm25_qc_masked`).
This affects exactly one run: **Kodungaiyur, 116.0 µg/m³ for 126 days (2022-01-01 → 2022-05-10)**, all in
the training period. Shorter runs (≤ 7 days) are kept.

## 7. Decisions

1. Original CSVs are never modified; all processing happens in `data/processed/`.
2. Each station is reindexed to a full daily calendar so gaps are explicit.
3. No backward fill, interpolation or centred windows. Labels are never imputed.
4. A forecast origin *t* is used only if PM2.5 was recorded on day *t* and day *t+1*.
5. Outliers, PM2.5 > PM10 rows and short constant runs are retained and documented.
6. The single 126-day constant PM2.5 run at Kodungaiyur is masked (documented QC rule above).

## 8. Figures

* `eda_pm25_timeseries.png`, `eda_pollutant_distributions.png`, `eda_missing_dates_heatmap.png`,
  `eda_correlation_heatmap.png`, `eda_seasonality_monthly.png`, `eda_station_boxplot.png`
"""
    (REPORTS_DIR / "data_audit.md").write_text(report, encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
